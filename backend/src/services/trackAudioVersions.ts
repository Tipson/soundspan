import { randomUUID } from "node:crypto";
import { mkdir, stat, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import type { Prisma } from "@prisma/client";
import axios from "axios";
import { parseFile } from "music-metadata";
import { z } from "zod";
import { config } from "../config";
import { prisma } from "../utils/db";
import { TRACK_VISIBLE_WHERE } from "../utils/librarySorting";
import { logger } from "../utils/logger";
import { loadMusicSourceAdapters } from "./musicSources/connections";
import { youtubeDownloadService } from "./youtubeDownload";

const log = logger.child("TrackAudioVersions");
const ids = {
    library: /^[A-Za-z0-9_-]{1,256}$/,
    youtube: /^[A-Za-z0-9_-]{11}$/,
    vk: /^-?\d{1,20}_\d{1,20}$/,
    yandex: /^\d{1,20}$/,
};

/** Portable, exact catalog identity. Titles and tags never identify the target. */
export const trackAudioTargetSchema = z
    .object({
        source: z.enum(["library", "youtube", "vk", "yandex"]),
        trackId: z.string().max(256),
    })
    .refine(({ source, trackId }) => ids[source].test(trackId));

/** An immutable id generated by the storage service for each upload. */
export const audioVersionIdSchema = z.uuidv4();
type Target = z.infer<typeof trackAudioTargetSchema>;
type Versions = { draftId: string | null; publishedId: string | null };

/** Typed failures which can be handled by the upload or publication UI. */
export class TrackAudioError extends Error {
    constructor(
        readonly kind: "invalid_audio" | "track_not_found" | "version_changed",
    ) {
        super(kind);
    }
}

/** Hidden, scanner-excluded directory on the shared music volume. */
export function trackAudioDirectory(): string {
    return resolve(config.music.musicPath, ".track-audio");
}

async function targetExists(
    { source, trackId }: Target,
    signal: AbortSignal,
): Promise<boolean> {
    if (source === "library") {
        return isVisibleLibraryTrack(trackId);
    }
    if (source === "youtube") {
        if (
            await prisma.trackYtMusic.findUnique({
                where: { videoId: trackId },
                select: { id: true },
            })
        ) {
            return true;
        }
        try {
            const info = await youtubeDownloadService.getVideoInfo(
                `https://www.youtube.com/watch?v=${trackId}`,
                signal,
            );
            return info.videoId === trackId && info.duration > 0;
        } catch (error) {
            if (axios.isAxiosError(error) && error.response?.status === 404)
                return false;
            throw error;
        }
    }
    const known = await prisma.trackMusicSource.findUnique({
        where: {
            provider_providerTrackId: {
                provider: source,
                providerTrackId: trackId,
            },
        },
        select: { verifiedMetadata: true },
    });
    if (known?.verifiedMetadata) return true;
    const adapter = (await loadMusicSourceAdapters()).find(
        (value) => value.enabled && value.provider === source,
    );
    const exact = await adapter?.lookup(trackId, signal);
    return exact?.id === trackId && exact.provider === source;
}

async function isVisibleLibraryTrack(trackId: string): Promise<boolean> {
    return Boolean(
        await prisma.track.findUnique({
            where: { id: trackId, ...TRACK_VISIBLE_WHERE },
            select: { id: true },
        }),
    );
}

async function transaction<T>(
    action: (tx: Prisma.TransactionClient) => Promise<T>,
): Promise<T> {
    for (let attempt = 0; ; attempt++) {
        try {
            return await prisma.$transaction(action, {
                isolationLevel: "Serializable",
            });
        } catch (error) {
            const code =
                typeof error === "object" && error !== null && "code" in error
                    ? error.code
                    : null;
            if (attempt >= 3 || (code !== "P2034" && code !== "P2002"))
                throw error;
        }
    }
}

async function removeFile(id: string): Promise<void> {
    if (!audioVersionIdSchema.safeParse(id).success) return;
    try {
        await unlink(resolve(trackAudioDirectory(), `${id}.mp3`));
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") {
            log.warn("Could not remove retired audio version", {
                error,
                versionId: id,
            });
        }
    }
}

/** Read publication state for an exact catalog identity without probing upstream. */
export async function readTrackAudioVersions(
    target: Target,
): Promise<Versions> {
    return (
        (await prisma.trackAudioVersion.findUnique({
            where: { source_trackId: target },
            select: { draftId: true, publishedId: true },
        })) ?? { draftId: null, publishedId: null }
    );
}

/** Point listeners at an on-disk publication, leaving broken rows visible to administrators. */
export async function readPublishedTrackAudio(
    target: Target,
): Promise<string | null> {
    const { publishedId } = await readTrackAudioVersions(target);
    if (!publishedId || !audioVersionIdSchema.safeParse(publishedId).success)
        return null;
    if (
        target.source === "library" &&
        !(await isVisibleLibraryTrack(target.trackId))
    )
        return null;
    try {
        const file = await stat(
            resolve(trackAudioDirectory(), `${publishedId}.mp3`),
        );
        return file.isFile() && file.size > 0 ? publishedId : null;
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
        throw error;
    }
}

/** Authorize a published stream or an administrator preview by immutable id. */
export async function canStreamTrackAudio(
    id: string,
    admin: boolean,
): Promise<boolean> {
    const where = admin
        ? { OR: [{ publishedId: id }, { draftId: id }] }
        : { publishedId: id };
    const track = await prisma.trackAudioVersion.findFirst({
        where,
        select: { source: true, trackId: true },
    });
    return (
        track !== null &&
        (track.source !== "library" ||
            (await isVisibleLibraryTrack(track.trackId)))
    );
}

/** Stage a supported MP3 only after validating the exact catalog entry and file. */
export async function stageTrackAudio(
    target: Target,
    bytes: Buffer,
    signal: AbortSignal,
): Promise<Versions> {
    if (!(await targetExists(target, signal)))
        throw new TrackAudioError("track_not_found");
    signal.throwIfAborted();
    const id = randomUUID();
    const directory = trackAudioDirectory();
    await mkdir(directory, { recursive: true });
    const path = resolve(directory, `${id}.mp3`);
    try {
        await writeFile(path, bytes, { flag: "wx", signal });
        let format;
        try {
            ({ format } = await parseFile(path, {
                duration: true,
                skipCovers: true,
            }));
        } catch {
            throw new TrackAudioError("invalid_audio");
        }
        if (
            format.container !== "MPEG" ||
            !format.codec?.endsWith("Layer 3") ||
            !Number.isFinite(format.duration) ||
            format.duration! < 1 ||
            format.duration! > 3600
        ) {
            throw new TrackAudioError("invalid_audio");
        }
        signal.throwIfAborted();
    } catch (error) {
        await removeFile(id);
        throw error;
    }

    // A database I/O error can leave the commit outcome unknown. Retain the
    // file in that event, because the committed row may already reference it.
    const { previousDraft, versions } = await transaction(async (tx) => {
        const where = { source_trackId: target };
        const previous = await tx.trackAudioVersion.findUnique({
            where,
            select: { draftId: true },
        });
        const versions = await tx.trackAudioVersion.upsert({
            where,
            create: { ...target, draftId: id },
            update: { draftId: id },
            select: { draftId: true, publishedId: true },
        });
        return { previousDraft: previous?.draftId, versions };
    });
    if (previousDraft) await removeFile(previousDraft);
    return versions;
}

/** Swap or withdraw publication only if the administrator's version is current. */
export async function setTrackAudioPublication(
    target: Target,
    id: string,
    publish: boolean,
): Promise<Versions> {
    const { retired, versions } = await transaction(async (tx) => {
        const where = { source_trackId: target };
        const row = await tx.trackAudioVersion.findUnique({ where });
        if (publish && row?.publishedId === id) {
            return {
                retired: null,
                versions: { draftId: row.draftId, publishedId: id },
            };
        }
        if (!row || (publish ? row.draftId : row.publishedId) !== id) {
            throw new TrackAudioError("version_changed");
        }
        const versions = await tx.trackAudioVersion.update({
            where,
            data: publish
                ? { draftId: null, publishedId: id }
                : { publishedId: null },
            select: { draftId: true, publishedId: true },
        });
        return { retired: row.publishedId, versions };
    });
    if (retired) await removeFile(retired);
    return versions;
}
